export function pathExists(obj, path) {
  if (!obj || typeof obj !== "object") return false;
  const parts = path.split(".");
  let cur = obj;
  for (const part of parts) {
    if (!cur || typeof cur !== "object" || !Object.prototype.hasOwnProperty.call(cur, part)) return false;
    cur = cur[part];
  }
  return true;
}

export function getPath(obj, path) {
  if (!obj || typeof obj !== "object") return undefined;
  return path.split(".").reduce((acc, key) => (acc == null ? undefined : acc[key]), obj);
}

export function setPath(obj, path, value) {
  const parts = path.split(".");
  let cur = obj;
  for (let i = 0; i < parts.length - 1; i += 1) {
    const key = parts[i];
    if (!cur[key] || typeof cur[key] !== "object" || Array.isArray(cur[key])) cur[key] = {};
    cur = cur[key];
  }
  cur[parts[parts.length - 1]] = value;
  return obj;
}

export function deletePath(obj, path) {
  const parts = path.split(".");
  const stack = [{ parent: obj, key: null, value: obj }];
  let cur = obj;
  for (let i = 0; i < parts.length; i += 1) {
    const key = parts[i];
    if (!cur || typeof cur !== "object" || !Object.prototype.hasOwnProperty.call(cur, key)) return false;
    stack.push({ parent: cur, key, value: cur[key] });
    cur = cur[key];
  }
  const leaf = stack[stack.length - 1];
  delete leaf.parent[leaf.key];
  for (let i = stack.length - 2; i >= 1; i -= 1) {
    const node = stack[i];
    if (node.value && typeof node.value === "object" && !Array.isArray(node.value) && Object.keys(node.value).length === 0) {
      delete node.parent[node.key];
    } else break;
  }
  return true;
}

export function valuesEqual(a, b) {
  if (Array.isArray(a) || Array.isArray(b)) {
    const left = Array.isArray(a) ? a.map(String) : [];
    const right = Array.isArray(b) ? b.map(String) : [];
    return left.length === right.length && left.every((item, i) => item === right[i]);
  }
  if (typeof a === "number" || typeof b === "number") {
    return Number(a) === Number(b);
  }
  return a === b;
}

export function isHhmm(value) {
  if (typeof value !== "string") return false;
  const match = value.trim().match(/^([01]\d|2[0-3]):([0-5]\d)$/);
  return !!match;
}

function bytesToMb(bytes) {
  const n = Number(bytes);
  if (!Number.isFinite(n)) return 0;
  return n / (1024 * 1024);
}

function msToMin(ms) {
  const n = Number(ms);
  if (!Number.isFinite(n)) return 0;
  return n / 60_000;
}

function msToSec(ms) {
  const n = Number(ms);
  if (!Number.isFinite(n)) return 0;
  return n / 1000;
}

