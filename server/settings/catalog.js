export function listCharacters(settings) {
  const seen = new Set();
  const out = [];
  for (const id of CHARACTER_ORDER) {
    const spec = settings?.characters?.[id];
    if (!spec) continue;
    seen.add(id);
    out.push({ id, name: spec.identity?.name || id });
  }
  for (const [id, spec] of Object.entries(settings?.characters ?? {})) {
    if (seen.has(id)) continue;
    out.push({ id, name: spec.identity?.name || id });
  }
  return out;
}

